/**
 * 管理画面に載せる操作マニュアル。
 * 本部（管理者・総代理店）向けと代理店・工務店向けで内容を分ける。
 * 画面を変えたらここも直す。特に手順の並びとメニュー名は画面と直結している。
 */

export type ManualBlock =
  | { t: 'p'; text: string }
  | { t: 'h3'; text: string }
  | { t: 'steps'; items: { title: string; note?: string }[] }
  | { t: 'list'; items: string[] }
  | { t: 'table'; head: string[]; rows: string[][] }
  | { t: 'flow'; rows: { who: string; what: string; mine?: boolean }[] }
  | { t: 'note'; tone: 'info' | 'caution' | 'stop'; title?: string; text: string }
  | { t: 'link'; href: string; label: string; description?: string };

export interface ManualSection {
  id: string;
  title: string;
  lead?: string;
  blocks: ManualBlock[];
}

