test('Chromium表示：現行価格の正式見積総額から得た増額・減額・標準・0円差額', async ({ page }) => {
  const cats = ['roof', 'toilet', 'bed', 'kitchen'].map(category);
  const opts = [
    option('roof-standard', 'roof', 10_000),
    option('roof-upgrade', 'roof', 30_000),
    option('toilet-standard', 'toilet', 20_000),
    option('toilet-economy', 'toilet', 15_000),
    option('bed-standard', 'bed', 6_000),
    option('kitchen-standard', 'kitchen', 18_000),
    option('kitchen-equal', 'kitchen', 18_000),
  ];
  const b = bundle(cats, opts);
  const current = ['roof-upgrade', 'toilet-economy', 'bed-standard', 'kitchen-equal'];
  const baseline = ['roof-standard', 'toilet-standard', 'bed-standard', 'kitchen-standard'];
  const evaluator = createSimulatorCardDeltaEvaluator({
    bundle: b, source: { kind: 'legacy', baseOverride: null },
    current: { optionIds: current, variantChoiceIds: [], exteriorFaces: [] },
    standard: { optionIds: baseline, variantChoiceIds: [], exteriorFaces: [] },
  });
  const total = (ids: string[]) => computePricing(b.model, b.options, b.categories,
    ids.map((option_id) => ({ option_id }))).total;
  const roof = evaluator.evaluate({ kind: 'category', categoryId: 'roof' });
  const toilet = evaluator.evaluate({ kind: 'category', categoryId: 'toilet' });
  expect(roof).toEqual({ kind: 'changed', deltaIncludingTax: total(current) -
    total(['roof-standard', 'toilet-economy', 'bed-standard', 'kitchen-equal']) });
  expect(toilet).toEqual({ kind: 'changed', deltaIncludingTax: total(current) -
    total(['roof-upgrade', 'toilet-standard', 'bed-standard', 'kitchen-equal']) });
  if (roof.kind !== 'changed' || toilet.kind !== 'changed') throw Error('exact prices expected');
  expect(roof.deltaIncludingTax).toBeGreaterThan(0);
  expect(toilet.deltaIncludingTax).toBeLessThan(0);
  const html = renderToStaticMarkup(realCreateElement(EquipmentBoard, {
    categories: cats, options: opts, selected: current, baselineSelected: baseline,
    readOnly: true, onPickCategory: () => {}, getCardDelta: evaluator.evaluate,
  }));
  const root = await inBrowser(page, html);
  const plus = root.getByTestId('equip-price-roof');
  const minus = root.getByTestId('equip-price-toilet');
  await expect(plus).toHaveText('＋' + roof.deltaIncludingTax.toLocaleString('ja-JP') + '円（税込）');
  await expect(minus).toHaveText('−' + Math.abs(toilet.deltaIncludingTax).toLocaleString('ja-JP') + '円（税込）');
  await expect(plus).toHaveAttribute('data-price-tone', 'increase');
  await expect(minus).toHaveAttribute('data-price-tone', 'decrease');
  await expect(plus).toHaveClass(/text-red-700/);
  await expect(minus).toHaveClass(/text-blue-700/);
  const red = await plus.evaluate((el) => getComputedStyle(el).color);
  const blue = await minus.evaluate((el) => getComputedStyle(el).color);
  expect(red).not.toBe(blue);
  await expect(root.getByTestId('equip-price-bed')).toHaveText('基本プランに含む');
  await expect(root.getByTestId('equip-price-kitchen')).toHaveText('変更しても差額なし');
});

