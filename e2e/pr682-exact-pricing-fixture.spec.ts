test('Chromium表示：v2.5の屋根23.5㎡と位置別サッシを正式税込見積総額と照合', async ({ page }) => {
  const cats = [category('roof'), category('sash')];
  const opts = [option('roof1', 'roof', 0, '㎡'), option('roof2', 'roof', 0, '㎡'),
    option('sash1', 'sash', 0), option('sash2', 'sash', 0)];
  const b = bundle(cats, opts);
  const selectedSlot = [{ slot_code: 'window-1', option_id: 'sash2', variant_choice_ids: [] }];
  const baseSlot = [{ slot_code: 'window-1', option_id: 'sash1', variant_choice_ids: [] }];
  const evaluator = createSimulatorCardDeltaEvaluator({
    bundle: b, source: { kind: 'sale-view', view: saleView, activeSlotCodes: ['window-1'] },
    current: { optionIds: ['roof2'], variantChoiceIds: [], exteriorFaces: [], slotSelections: selectedSlot },
    standard: { optionIds: ['roof1'], variantChoiceIds: [], exteriorFaces: [], slotSelections: baseSlot },
  });
  const total = (roof: string, slots: typeof selectedSlot) =>
    computeSaleViewPricing(b, saleView, [roof], [], [], undefined, slots);
  const now = total('roof2', selectedSlot);
  const roofRestored = total('roof1', selectedSlot);
  const slotRestored = total('roof2', baseSlot);
  expect(now.missing_units).toHaveLength(0);
  const roofResult = evaluator.evaluate({ kind: 'category', categoryId: 'roof' });
  const slotResult = evaluator.evaluate({ kind: 'slot', slotCode: 'window-1' });
  expect(roofResult).toEqual({ kind: 'changed', deltaIncludingTax: now.pricing.total - roofRestored.pricing.total });
  expect(slotResult).toEqual({ kind: 'changed', deltaIncludingTax: now.pricing.total - slotRestored.pricing.total });
  if (roofResult.kind !== 'changed' || slotResult.kind !== 'changed') throw Error('exact v2.5 price expected');
  const tiles: EquipmentSlotTile[] = [{
    slotCode: 'window-1', categoryId: 'sash', label: '窓①', option: opts[3], variantNames: [],
  }];
  const html = renderToStaticMarkup(realCreateElement(EquipmentBoard, {
    categories: cats, options: opts, selected: ['roof2'], baselineSelected: ['roof1'],
    slotTiles: tiles, readOnly: true, onPickCategory: () => {}, getCardDelta: evaluator.evaluate,
  }));
  const root = await inBrowser(page, html);
  await expect(root.getByTestId('equip-price-roof')).toHaveText(
    '＋' + roofResult.deltaIncludingTax.toLocaleString('ja-JP') + '円（税込）');
  await expect(root.getByTestId('equip-slot-price-window-1')).toHaveText(
    '＋' + slotResult.deltaIncludingTax.toLocaleString('ja-JP') + '円（税込）');
});
