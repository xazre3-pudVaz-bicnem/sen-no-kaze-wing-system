export function manualFor(role: RoleCode): { title: string; lead: string; sections: ManualSection[] } {
  if (role === 'dealer') {
    return {
      title: '操作マニュアル（代理店・工務店）',
      lead: '担当のお客様に確定見積をお出しするまでの手順です。',
      sections: DEALER_MANUAL,
    };
  }
  return {
    title: role === 'admin' ? '操作マニュアル（本部）' : '操作マニュアル（総代理店）',
    lead: '受注の流れと、商品台帳・権限・見積の扱い方です。',
    sections: HQ_MANUAL,
  };
}
