async function inBrowser(page: Page, html: string) {
  await page.goto('/simulator/wing-01');
  await expect(page.getByTestId('simulator')).toHaveAttribute('data-hydrated', 'true');
  await page.locator('body').evaluate((node, markup) => {
    const section = document.createElement('section');
    section.id = 'price-fixture';
    section.style.cssText = 'position:relative;z-index:999;background:white;max-width:960px;margin:20px auto;padding:16px';
    section.innerHTML = markup;
    node.appendChild(section);
  }, html);
  return page.locator('#price-fixture');
}
